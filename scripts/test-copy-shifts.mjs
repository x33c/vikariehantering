import assert from 'node:assert/strict';
import vm from 'node:vm';
import ts from 'typescript';
import { readFileSync } from 'node:fs';
import { webcrypto } from 'node:crypto';
const ctx = { exports: {}, crypto: webcrypto };
vm.runInNewContext(ts.transpileModule(readFileSync('src/lib/copyShifts.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, ctx);
const { planShiftCopies: plan, copyConflicts: conflicts, monday } = ctx.exports;
const source = { id: 'original', datum: '2026-10-23', tid_från: '08:00:00', tid_till: '16:30:00', personal_id: 'teacher', vikarie_id: 'sub', status: 'bekräftat', grupp: '1A', frånvaro_id: 'absence', schemarad_id: 'schedule', riktad_till_vikarie_id: 'offer', publicerad: true, anteckning: 'Private old note', typ: 'del_av_dag', ämne: null, sal: null };
const copies = plan([source], ['2026-10-26', '2026-11-02'], false, '2026-10-06');
assert.deepEqual(Array.from(copies, p => p.datum), ['2026-10-30', '2026-11-06'], 'Same weekday across DST');
for (const p of copies) {
  assert.equal(p.tid_från, source.tid_från);
  assert.equal(p.status, 'obokat');
  assert.equal(p.vikarie_id, null);
  assert.equal(p.publicerad, false);
  for (const key of ['frånvaro_id', 'schemarad_id', 'riktad_till_vikarie_id', 'anteckning']) assert.equal(p[key], null);
  assert.notEqual(p.id, source.id);
}
assert.equal(source.status, 'bekräftat');
assert.equal(monday('2027-01-01'), '2026-12-28');
const booked = plan([source], ['2026-12-28'], true, '2026-10-06')[0];
assert.equal(booked.datum, '2027-01-01');
assert.equal(booked.status, 'bokat');
assert.equal(booked.vikarie_id, 'sub');
assert.equal(plan([{ ...source, status: 'notifierat' }], ['2026-10-26'], true, '2026-10-06')[0].vikarie_id, null);
assert.throws(() => plan([source, { ...source, datum: '2026-10-30' }], ['2026-11-02'], false, '2026-10-06'));
assert.throws(() => plan([source], [], false, '2026-10-06'));
assert.throws(() => plan([source], ['2026-10-19'], false, '2026-10-06'));
assert.throws(() => plan([{ ...source, status: 'avbokat' }], ['2026-10-26'], false, '2026-10-06'));
assert.throws(() => plan([source], ['2026-10-26'], false, '2026-11-01'));
assert.equal(conflicts(copies, [], new Set()).length, 0);
assert.equal(conflicts(copies, [], new Set(['2026-10-30'])).length, 1);
assert.equal(conflicts(copies, [{ ...copies[0], id: 'existing' }], new Set()).length, 1);
assert.equal(conflicts([booked], [{ ...booked, personal_id: 'other', id: 'existing' }], new Set()).length, 1);
assert.equal(conflicts(copies, [{ ...copies[0], status: 'avbokat' }], new Set()).length, 0);
assert.equal(conflicts(copies, [{ ...copies[0], tid_från: '16:30:00', tid_till: '17:00:00' }], new Set()).length, 0);
assert.equal(conflicts([copies[0], { ...copies[0], id: 'another' }], [], new Set()).length, 1);
const standalone = { ...copies[0], personal_id: null };
assert.equal(conflicts([standalone], [standalone], new Set()).length, 1);
console.log('PASS: week copying, DST/year boundaries, safe fields, bookings, conflicts, locks and validation');
